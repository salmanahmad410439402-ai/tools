/**
 * Writes `app/font-library.css` from the editor's font registry.
 *
 * The editor previews text with the same family that gets embedded in the PDF,
 * so each library family needs an `@font-face` rule. Keeping the CSS generated
 * means the registry stays the single source of truth: adding a family to
 * `lib/pdf/font-library.ts` and its files to `public/fonts/library/` is all it
 * takes, and a missing file is a build error rather than a silent fallback.
 *
 * Run with: node --experimental-strip-types scripts/build-font-css.ts
 */
import { writeFileSync, existsSync, statSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

import { LIBRARY_FONTS, fontFileUrl, type FontStyleKey } from "../lib/pdf/font-library.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "app", "font-library.css");

// The latin range the files were trimmed to. Declaring it means the browser
// falls back to the UI font for characters the file cannot draw, instead of
// rendering empty boxes — the same substitution the exporter makes.
const UNICODE_RANGE = [
  "U+0000-00FF",
  "U+0131",
  "U+0152-0153",
  "U+02BB-02BC",
  "U+02C6",
  "U+02DA",
  "U+02DC",
  "U+2000-206F",
  "U+2074",
  "U+20AC",
  "U+2122",
  "U+2191",
  "U+2193",
  "U+2212",
  "U+2215",
  "U+FEFF",
  "U+FFFD",
].join(", ");

const WEIGHT: Record<FontStyleKey, { weight: number; style: "normal" | "italic" }> = {
  regular: { weight: 400, style: "normal" },
  bold: { weight: 700, style: "normal" },
  italic: { weight: 400, style: "italic" },
  boldItalic: { weight: 700, style: "italic" },
};

const blocks: string[] = [];
const missing: string[] = [];

for (const font of LIBRARY_FONTS) {
  for (const style of font.styles) {
    const woff2 = path.join(root, "public", fontFileUrl(font.id, style).replace(/\.ttf$/, ".woff2"));
    const ttf = path.join(root, "public", fontFileUrl(font.id, style));
    if (!existsSync(woff2) || statSync(woff2).size < 1000) missing.push(path.relative(root, woff2));
    if (!existsSync(ttf) || statSync(ttf).size < 1000) missing.push(path.relative(root, ttf));

    const { weight, style: slant } = WEIGHT[style];
    blocks.push(
      [
        "@font-face {",
        `  font-family: 'FC ${font.label}';`,
        `  font-style: ${slant};`,
        `  font-weight: ${weight};`,
        "  font-display: swap;",
        `  src: url('${fontFileUrl(font.id, style).replace(/\.ttf$/, ".woff2")}') format('woff2');`,
        `  unicode-range: ${UNICODE_RANGE};`,
        "}",
      ].join("\n"),
    );
  }
}

if (missing.length) {
  console.error("Missing font files for the editor library:\n" + missing.map((file) => `  ${file}`).join("\n"));
  process.exit(1);
}

const css = `/* Generated by scripts/build-font-css.mjs — do not edit by hand. */

/*
 * Editor font library. Each rule points at the same family the PDF exporter
 * embeds, so the page preview and the downloaded file agree. Fonts load on
 * demand: the browser only fetches a family once text actually uses it.
 */

${blocks.join("\n\n")}
`;

writeFileSync(out, css);
console.log(`Wrote ${path.relative(root, out)} — ${LIBRARY_FONTS.length} families, ${blocks.length} faces.`);
